import { eq } from "drizzle-orm";

import { db } from "../index";
import { user } from "../schema/auth";

export interface SeedSuperadminOptions {
  email: string;
  name?: string;
}

export interface SeedSuperadminResult {
  user: typeof user.$inferSelect;
  isNew: boolean;
  elevated: boolean;
}

/**
 * Idempotently creates or elevates a user to platform superadmin.
 */
export async function seedSuperadmin(
  options: SeedSuperadminOptions,
): Promise<SeedSuperadminResult> {
  const normalizedEmail = options.email.toLowerCase().trim();
  const name = options.name?.trim() || "Super Admin";

  // 1. Check if user already exists
  const existingUser = await db.query.user.findFirst({
    where: (table, { eq }) => eq(table.email, normalizedEmail),
  });

  if (existingUser) {
    const needsElevation =
      existingUser.role !== "admin" ||
      existingUser.status !== "active" ||
      !existingUser.emailVerified;

    if (needsElevation) {
      const [updatedUser] = await db
        .update(user)
        .set({
          role: "admin",
          status: "active",
          emailVerified: true,
          updatedAt: new Date(),
        })
        .where(eq(user.id, existingUser.id))
        .returning();

      return {
        user: updatedUser ?? existingUser,
        isNew: false,
        elevated: true,
      };
    }

    return {
      user: existingUser,
      isNew: false,
      elevated: false,
    };
  }

  // 2. Insert new superadmin (ID is auto-generated by Drizzle $defaultFn)
  const [newUser] = await db
    .insert(user)
    .values({
      email: normalizedEmail,
      name,
      role: "admin",
      status: "active",
      emailVerified: true,
    })
    .returning();

  if (!newUser) {
    throw new Error(`Failed to create superadmin user for ${normalizedEmail}`);
  }

  return {
    user: newUser,
    isNew: true,
    elevated: false,
  };
}
